"""Формирование ВОР по типовому шаблону (вкладка «Формирование ВОР»).

Пакет собирает ведомость объёмов работ по типовому шаблону
``data/Типовой ВОР по КР.xlsx`` (лист ``ВОР КР_ЖС``) на основании
загруженной цифровой модели (IFC) и сопутствующих документов
(ПОС, ВОР застройщика, ПЗ, ПД).

Состав пакета:

* :mod:`mapping`   — правила сопоставления текстов типового ВОР с типами
  конструкций и видами объёмов;
* :mod:`template`  — разбор шаблона и рендер заполненного файла;
* :mod:`elements`  — индексация элементов IFC из «сырого» дампа и агрегация
  объёмов по группам;
* :mod:`documents` — извлечение данных из ПОС/ВОР/ПЗ/ПД (в первую очередь —
  арматуры из ВОР застройщика);
* :mod:`builder`   — сборка заполненного типового ВОР;
* :mod:`customer_vor` — приведение ВОР заказчика (PDF) к структуре типового ВОР
  (``ВОР_заказчика.xlsx``);
* :mod:`manager`   — жизненный цикл задачи формирования ВОР (загрузка файлов,
  фоновая обработка, статусы, выдача результата).
"""

